@ Data field support: the pane class table itself is generated by build.py
@ (out/pane_table.S) from the firmware's own table filler, because the stock
@ table is not in descriptor order (ids 90-91 -> descriptors 159-160, ids
@ 92-160 -> descriptors 90-158).

    .syntax unified
    .arm

@ "Change Info Fields" preselect: replaces the counting loop at 0x300930AC.
@ In: r0 = descriptor of the focused cell. Out: r0 = its position in the
@ picker list. Callee-saved registers are preserved by the C code.
    .section .text.hooks_fields, "ax"
    .global picker_index_tramp
picker_index_tramp:
    push    {r4, lr}
    mov     r4, sp
    bic     sp, sp, #7
    bl      field_picker_index
    mov     sp, r4
    pop     {r4, pc}
