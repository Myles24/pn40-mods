def clock_patches():
    """Boot-time clock literals of the firmware's startup code (each loaded by
    exactly one ldr: 0x300818A4, 0x300818AC, 0x30081940)."""
    if not CPU_CLOCK:
        return []
    hclk = CPU_CLOCK["src_cr_hclk"] << 13
    return [
        ("SRC_PLLFR (PLL1/PLL2 frequency)", 0x30081B90, le32(0x16002203), le32(CPU_CLOCK["pllfr"])),
        ("SRC_CR first write (HCLK divider)", 0x30081B94, le32(0x00002004), le32(0x00000004 | hclk)),
        ("SRC_CR final write (HCLK divider)", 0x30081BA8, le32(0x00002104), le32(0x00000104 | hclk)),
    ]


def basedata_patches():
    """Every use of the base map folder (scans, the licence exemption prefix
    test at 0x300AA338, the path tables) reads the one string at 0x304D0C80;
    the tide and time zone files have their own strings and stay on MSYS0.
    The folder flag (2 = basedata, 1 = SD, 4 = MSYS2) still says "basedata",
    so exporting the SD card over USB must also drop flag 2."""
    if not BASEDATA_ON_SD:
        return []
    return [
        ("base map folder MSYS0:/basedata -> SD:/basedata", 0x304D0C80, b"MSYS0:/basedata\0",
         b"SD:/basedata\0\0\0\0"),
        # USB export of the SD card closes the maps under this prefix
        # (0x30313930, prefix compare); "SD:/maps" -> "SD:/" (0x305D2CCC)
        ("SD export closes SD:/ maps, not only SD:/maps", 0x300AAFB0, le32(0x304D0C18), le32(0x305D2CCC)),
        # ...and keeps the catalogue entries of the folders still mounted:
        # 6 (basedata + MSYS2) -> 4 (MSYS2), in both export handlers
        ("SD export keeps MSYS2 maps only (0x300A97C4)", 0x300AAF78, le32(0x03A01006), le32(0x03A01004)),
        ("SD export rescans MSYS2 only (0x300A6E58)", 0x300A753C, le32(0x03A01006), le32(0x03A01004)),
    ]


def check_code_area_unused(stock_hex):
    """No constant that firmware code loads (ARM "ldr rX, [pc, #imm]") may point
    into the area the mods occupy. Plain words in that range are instructions
    or data that only look like addresses."""
    base, img = pnhex.image(open(stock_hex, "rb").read())
    lo, hi = 0x306D0000, pnhex.SAFE_END
    for o in range(0, len(img) - 3, 4):
        w = struct.unpack_from("<I", img, o)[0]
        if (w & 0x0F7F0000) != 0x051F0000 or (w >> 28) == 0xF:
            continue
        imm = w & 0xFFF
        lit = o + 8 + (imm if (w >> 23) & 1 else -imm)
        if 0 <= lit <= len(img) - 4:
            v = struct.unpack_from("<I", img, lit)[0]
            if lo <= v < hi:
                sys.exit("firmware code at %08X loads %08X, inside the mod area" % (base + o, v))


def emulate_bootloader(lines):
    """Run the bootloader's own line parser (RAM 0x842C) on each line."""
    try:
        import unicorn
        from unicorn.arm_const import UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3, \
            UC_ARM_REG_SP, UC_ARM_REG_LR
    except ImportError:
        print("  (unicorn not installed: skipping bootloader emulation)")
        return
    nor_path = os.path.join(HERE, "..", "nor", "nor_8MB.bin")
    if not os.path.exists(nor_path):
        print("  (no NOR dump: skipping bootloader emulation)")
        return
    nor = open(nor_path, "rb").read()
    mu = unicorn.Uc(unicorn.UC_ARCH_ARM, unicorn.UC_MODE_ARM)
    mu.mem_map(0, 0x200000)
    mu.mem_write(0x72BC, nor[0x11A0:0x11A0 + (0x442E8 - 0x72BC)])
    mu.mem_write(0x442E8, nor[0x3E970:0x3E970 + (0x4FDD4 - 0x442E8)])
    mu.mem_map(0x30000000, 0x800000)
    mu.mem_write(0x30000000, nor)
    LINE, OUT, RET, STACK = 0x180000, 0x181000, 0x1F0000, 0x1EF000

    def call(args):
        for reg, v in zip((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3), args):
            mu.reg_write(reg, v)
        mu.reg_write(UC_ARM_REG_SP, STACK)
        mu.reg_write(UC_ARM_REG_LR, RET)
        mu.emu_start(0x842C, RET, count=2000000)
        return mu.reg_read(UC_ARM_REG_R0)

    call((0, 0, 0, 0))                                   # reset "last address"
    for n, text in lines:
        mu.mem_write(LINE, text + b"\0")
        if call((LINE, OUT, OUT + 4, OUT + 8)) != 1:
            sys.exit("bootloader parser REJECTS line %d: %r" % (n, text))
        addr, count = struct.unpack("<Ii", bytes(mu.mem_read(OUT, 8)))
        want = text.split()
        if addr != int(want[0], 16) or count != len(want) - 1 or \
                bytes(mu.mem_read(OUT + 8, count)) != bytes(int(x, 16) for x in want[1:]):
            sys.exit("bootloader parser misreads line %d: %r" % (n, text))


def set_build_id(code, syms, patches):
    """mods_build_id (prof.c, shown in the diagnostics reports) = first 32 bits
    of sha256 over the code (with the placeholder) and every patch."""
    off = syms["mods_build_id"] - 0x306D0000
    if code[off:off + 4] != le32(0xFFFFFFFF):
        sys.exit("mods_build_id placeholder not found")
    h = hashlib.sha256(code)
    for name, addr, old, new in patches:
        h.update(le32(addr) + bytes(new))
    bid = int(h.hexdigest()[:8], 16)
    return code[:off] + le32(bid) + code[off + 4:], bid


def write_delta(out, base, data, digest):
    """Second output: only the 64 KB blocks that differ from base (the build
    installed on the device), each block complete; checked to flash exactly
    like the full file."""
    base_data = open(base, "rb").read()
    pnhex.validate(base_data)
    d, blocks = pnhex.delta(base_data, data)
    if not d:
        print("delta: nothing differs from %s" % base)
        return
    pnhex.validate(d)
    pnhex.check_delta(base_data, data, d)
    lines = [(n, raw) for n, raw in enumerate(d.split(b"\r\n"), 1) if raw]
    emulate_bootloader(lines)
    base_sha = hashlib.sha256(base_data).hexdigest()
    path = os.path.join(out, "PN-40.delta-from-%s.hex" % base_sha[:8])
    open(path, "wb").write(d)
    print("wrote %s\n  %d blocks (%s), %d lines (full file: %d); base %s..., result %s...\n"
          "  checked: base + delta flashes exactly like the full file; bootloader parser accepts every line\n"
          "  sha256 %s" % (path, len(blocks), " ".join("%X" % (b * 0x10000) for b in blocks), len(lines),
                           data.count(b"\n"), base_sha[:8], digest[:8], hashlib.sha256(d).hexdigest()))


def main(stock, out, base=None):
    os.makedirs(out, exist_ok=True)
    code, syms = compile_mods(out, stock)
    print("compiled: %d bytes at 0x306D0000" % len(code))
    if syms["pane_table_end"] - syms["pane_table"] != 4 * PANE_TABLE_LEN:
        sys.exit("pane_table has %d entries, expected %d"
                 % ((syms["pane_table_end"] - syms["pane_table"]) // 4, PANE_TABLE_LEN))
    check_code_area_unused(stock)

    hx = pnhex.HexFile(stock)
    for name, addr, old, new in make_patch.PATCHES:
        hx.patch(name, addr, bytes.fromhex(old), bytes.fromhex(new))
        print("patched: %s @ %08X" % (name, addr))
    patches = mod_patches(syms)
    for name, addr, old, new in patches:
        hx.patch(name, addr, old, new)
        print("patched: %s @ %08X" % (name, addr))
    code, bid = set_build_id(code, syms, patches)
    print("build id %08X" % bid)
    hx.append("mods code", 0x306D0000, code)

    data = hx.render()
    count, lo, hi = pnhex.validate(data)
    print("format/safety check OK: %d records, %08X-%08X" % (count, lo, hi))

    stock_lines = open(stock, "rb").read().split(b"\n")
    changed = []
    for n, raw in enumerate(data.split(b"\n"), 1):
        if n > len(stock_lines) or raw != stock_lines[n - 1]:
            if raw.strip():
                changed.append((n, raw.rstrip(b"\r")))
    emulate_bootloader(changed)
    print("bootloader parser accepts all %d changed/new lines" % len(changed))

    with open(os.path.join(out, "symbols.txt"), "w") as f:
        for name, addr in sorted(syms.items(), key=lambda kv: kv[1]):
            f.write("%08X %s\n" % (addr, name))
    dst = os.path.join(out, "PN-40.hex")
    digest = hx.write(dst)
    print("wrote %s\n  sha256 %s" % (dst, digest))
    if base:
        write_delta(out, base, hx.render(), digest)


