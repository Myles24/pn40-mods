"""Build PN-40.hex with the mods in this folder.

usage: python build.py <stock PN-40.hex> [output dir, default .\\out] [--base <installed PN-40.hex>]

Steps:
  1. compile nmealog.c + hooks.S, link at 0x306D0000 (fw.ld)
  2. apply ..\\patched\\make_patch.py PATCHES (GPS week rollover fix)
  3. apply the hook patches below (each checks the stock bytes first)
  4. append the compiled code as new records
  5. check the result: format/safety rules (pnhex.validate) and the
     bootloader's own line parser, run in an emulator on every changed line
Needs arm-none-eabi-gcc (MSYS2: mingw-w64-x86_64-arm-none-eabi-gcc) and,
for step 5, the NOR dump in ..\\nor plus the unicorn package.
"""
import hashlib
import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "patched"))
import pnhex
import make_patch

TOOLS = r"C:\msys64\mingw64\bin"
CFLAGS = ["-mcpu=arm926ej-s", "-marm", "-mfloat-abi=soft", "-Os", "-ffreestanding", "-fno-builtin",
          "-fno-tree-loop-distribute-patterns", "-fno-common", "-fno-pic", "-ffunction-sections",
          "-fstack-usage", "-Wall", "-Wextra", "-Werror"]
# nmealog_append runs on the NMEA output task's 0x76C-byte stack
# bbox_watchdog runs on the watchdog task's 0x400-byte stack
STACK_LIMITS = {"nmealog_append": 128, "nmealog_init": 128, "ascent_init": 128, "profile_init": 128, "prof_init": 128,
                "bbox_init": 128, "bbox_watchdog": 64, "bbox_reset": 64, "bbox_shutdown": 128}
SOURCES = ["hooks.S", "nmealog.c", "fields.S", "battfield.c", "ascent.c", "profile.c", "prof_hooks.S", "prof.c",
           "bbox_hooks.S", "bbox.c"]
PANE_TABLE_LEN = 164                    # must match fw.h

# CPU clock (see README "CPU clock"): the boot code sets SRC_PLLFR and SRC_CR
# once. Stock: PLL1 = 26 MHz * 36 >> 3 = 117 MHz, HCLK field (SRC_CR 14:13) 1.
# 175.5 MHz = 26 * 27 >> 2 with HCLK field 2 keeps the bus at 58.5 MHz if the
# field means /(n+1), or makes it slower (87.75 MHz) if it means /n.
# None = stock clock.
CPU_CLOCK = {"pllfr": 0x16002202, "src_cr_hclk": 3}
# 234 MHz = 26 * 36 >> 2 (the stock PLL VCO, one shift less) with the bus at
# /4 = 58.5 MHz, unchanged (the HCLK field means /(n+1), measured). It passed
# the stress test; one report once came out with 7 characters missing.
# 175.5 MHz = {"pllfr": 0x16001902, "src_cr_hclk": 2}.
# Known issue at both: the unit shuts down when "Connect to Computer" exports
# the SD card (bbox.c records why). The compass once looked broken at 175.5
# MHz; that was local magnetic interference, but the compass task retry patch
# in mod_patches stays as a safeguard.

# Base map folder on the SD card (see README "Base maps on the SD card"):
# MSYS0:/basedata -> SD:/basedata, so maps from public data (mapgen/) are
# limited by the card's size instead of MSYS0's 85 MB. False = stock.
BASEDATA_ON_SD = True


def tool(name):
    for p in (os.path.join(TOOLS, name + ".exe"), shutil.which(name) or ""):
        if p and os.path.exists(p):
            return p
    sys.exit("%s not found; install the MSYS2 package mingw-w64-x86_64-arm-none-eabi-gcc" % name)


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit("command failed: %s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
    return r.stdout


OUR_FIELDS = ["battfield_desc", "ascent_desc", "descent_desc"]   # ids 161.. in this order; never renumber
# stock pane classes whose descriptor we replace (same id, so page_state.dat is unaffected):
# the Hunt/Fish page's widgets 84-89 (profile.c takes the page over)
PANE_OVERRIDES = {i: "profile_pane_desc" for i in range(84, 90)}


def stock_pane_table(stock_hex):
    """Run the firmware's pane class table filler (0x3008FFC8) and return the
    161 pointers it stores at 0x00054580. The order is NOT simply
    0x53B70 + 16*i, so never hand-write this table."""
    import unicorn
    from unicorn.arm_const import UC_ARM_REG_SP, UC_ARM_REG_LR
    base, img = pnhex.image(open(stock_hex, "rb").read())
    mu = unicorn.Uc(unicorn.UC_ARCH_ARM, unicorn.UC_MODE_ARM)
    mu.mem_map(0x30000000, 0x800000)
    mu.mem_write(base, bytes(img))
    mu.mem_map(0, 0x800000)
    mu.reg_write(UC_ARM_REG_SP, 0x700000)
    mu.reg_write(UC_ARM_REG_LR, 0x10000)
    mu.emu_start(0x3008FFC8, 0x10000, count=100000)
    tab = list(struct.unpack("<161I", bytes(mu.mem_read(0x00054580, 161 * 4))))
    if sorted(tab) != [0x00053B70 + 16 * i for i in range(161)]:
        sys.exit("pane class table filler did not produce 161 distinct descriptors")
    return tab


def write_pane_table(out, tab):
    lines = ["@ generated by build.py from the stock table filler 0x3008FFC8 -- do not edit",
             "    .section .rodata.pane_table, \"a\"", "    .balign 4", "    .global pane_table", "pane_table:"]
    lines += ["    .word %s            @ %d (stock 0x%08X)" % (PANE_OVERRIDES[i], i, v) if i in PANE_OVERRIDES
              else "    .word 0x%08X            @ %d" % (v, i) for i, v in enumerate(tab)]
    lines += ["    .word %s            @ %d" % (s, 161 + k) for k, s in enumerate(OUR_FIELDS)]
    lines += ["    .global pane_table_end", "pane_table_end:", ""]
    path = os.path.join(out, "pane_table.S")
    open(path, "w").write("\n".join(lines))
    return path


def compile_mods(out, stock_hex):
    gcc = tool("arm-none-eabi-gcc")
    objs = []
    tab = stock_pane_table(stock_hex)
    srcs = [os.path.join(HERE, s) for s in SOURCES] + [write_pane_table(out, tab)]
    for src in srcs:
        obj = os.path.join(out, os.path.splitext(os.path.basename(src))[0] + ".o")
        run(gcc, *CFLAGS, "-c", src, "-o", obj)
        objs.append(obj)
        su = obj[:-2] + ".su"
        if os.path.exists(su):
            for line in open(su):
                fn, size, kind = line.rsplit(None, 2)
                fn = fn.rsplit(":", 1)[-1]
                if fn in STACK_LIMITS and (int(size) > STACK_LIMITS[fn] or kind != "static"):
                    sys.exit("%s uses %s bytes of stack (%s), limit %d" % (fn, size, kind, STACK_LIMITS[fn]))
                print("  stack %-18s %4s bytes" % (fn, size))
    elf = os.path.join(out, "mods.elf")
    # no -lgcc on purpose: a libgcc call (e.g. a division helper) fails the link
    run(gcc, *CFLAGS, "-nostdlib", "-T", os.path.join(HERE, "fw.ld"), "-Wl,-Map=" + os.path.join(out, "mods.map"),
        "-Wl,--gc-sections", *objs, "-o", elf)
    binf = os.path.join(out, "mods.bin")
    run(tool("arm-none-eabi-objcopy"), "-O", "binary", "-j", ".text", elf, binf)
    syms = {}
    for line in run(tool("arm-none-eabi-nm"), elf).splitlines():
        parts = line.split()
        if len(parts) == 3:
            syms[parts[2]] = int(parts[0], 16)
    code = open(binf, "rb").read()
    # the linked table must equal the firmware's for every stock id
    off = syms["pane_table"] - 0x306D0000
    linked = list(struct.unpack_from("<%dI" % PANE_TABLE_LEN, code, off))
    want = [syms[PANE_OVERRIDES[i]] if i in PANE_OVERRIDES else v for i, v in enumerate(tab)]
    if linked[:161] != want:
        bad = [i for i in range(161) if linked[i] != want[i]]
        sys.exit("pane_table differs from the stock table at ids %s" % bad[:10])
    if linked[161:] != [syms[s] for s in OUR_FIELDS]:
        sys.exit("pane_table extra entries don't match OUR_FIELDS")
    print("pane_table: ids 0-160 identical to the stock table except overrides %s, %d new field(s)"
          % (sorted(PANE_OVERRIDES), len(OUR_FIELDS)))
    return code, syms


def le32(v):
    return struct.pack("<I", v)


def arm_b(site, target, link=False):
    off = target - (site + 8)
    assert off % 4 == 0 and -(1 << 25) <= off < (1 << 25)
    return le32((0xEB000000 if link else 0xEA000000) | ((off >> 2) & 0xFFFFFF))


def arm_bl(site, target):
    return arm_b(site, target, link=True)


